_DOCUMENTS = _documents()
_VECTORS = _vectors()


@pytest.mark.parametrize("name", sorted(_DOCUMENTS))
def test_canonical_bytes_match_the_backend_fixture(name: str) -> None:
    produced = canonical_json_bytes(_DOCUMENTS[name]).decode("utf-8")

    assert produced == _VECTORS[name]["CanonicalJson"]


@pytest.mark.parametrize("name", sorted(_DOCUMENTS))
def test_digest_matches_the_backend_fixture(name: str) -> None:
    assert compute_digest(_DOCUMENTS[name]) == _VECTORS[name]["Digest"]


def test_the_fixture_itself_carries_the_contract_digest() -> None:
    """A truncated or hand-edited fixture cannot silently become the reference."""

    document = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert len(document["Vectors"]) == 9
    assert document["ContractDigest"]


def test_a_divergent_value_produces_a_divergent_digest() -> None:
    """A one-character difference must not hash to the same digest as the fixture."""

    base = compute_digest(_DOCUMENTS["divergentDigest"])
    changed = compute_digest({"value": "Studio One"})

    assert base == _VECTORS["divergentDigest"]["Digest"]
    assert changed != base


def test_timestamps_with_the_same_instant_but_a_different_offset_differ() -> None:
    """Offset text is preserved, so 00:01:59Z and 02:01:59+02:00 are different documents."""

    utc = compute_digest({"at": "2026-11-16T00:01:59+00:00"})
    offset = compute_digest({"at": "2026-11-16T02:01:59+02:00"})

    assert utc != offset


def test_a_non_finite_number_is_refused() -> None:
    with pytest.raises(BackendCanonicalError) as captured:
        canonical_json_bytes({"latitude": float("nan")})

    assert captured.value.code == "BACKEND_DECIMAL_NOT_FINITE"


def test_two_keys_that_normalize_together_are_refused() -> None:
    with pytest.raises(BackendCanonicalError) as captured:
        canonical_json_bytes({"caf\u00e9": 1, "cafe\u0301": 2})

    assert captured.value.code == "BACKEND_KEY_COLLISION"
